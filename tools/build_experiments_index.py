#!/usr/bin/env python3
"""Evidence Library index generator for xdna-top.

Scans every experiment report under ``docs/experiments/*.md`` for its YAML
front-matter and produces two things, deterministically and idempotently:

1. ``docs/experiments/index.md`` — a generated table of all experiments.
2. An "Evidence Library" section injected into ``docs/index.html`` between
   ``<!-- EVIDENCE-LIBRARY:START -->`` / ``<!-- EVIDENCE-LIBRARY:END -->``
   markers (inserted before ``</body>`` on first run).

New experiment docs auto-appear with no hand-editing. Re-running the generator
on an up-to-date tree produces no diff (idempotent).

Front-matter convention (one block at the top of each experiment doc):

    ---
    title: <human title>
    date: <YYYY-MM-DD>
    kernel: <uname -r>
    hardware: <SoC / board>
    xrt_version: <xrt-smi version>
    headline: <one-line finding>
    artifacts:
      - artifacts/<raw snapshot/record json>
    ---

The generator scans only the public ``docs/experiments/`` tree. It never reads
anything outside this repository.

Usage::

    python tools/build_experiments_index.py            # write index.md + inject HTML
    python tools/build_experiments_index.py --check     # exit 1 if outputs are stale
"""

from __future__ import annotations

import argparse
import sys
import yaml
from dataclasses import dataclass, field
from pathlib import Path

HTML_START = "<!-- EVIDENCE-LIBRARY:START (generated by tools/build_experiments_index.py) -->"
HTML_END = "<!-- EVIDENCE-LIBRARY:END -->"
GENERATED_NOTE = "<!-- generated by tools/build_experiments_index.py — do not edit by hand -->"

SCALAR_KEYS = ("title", "date", "kernel", "hardware", "xrt_version", "headline")


@dataclass
class Experiment:
    slug: str
    title: str
    date: str
    kernel: str
    hardware: str
    xrt_version: str
    headline: str
    artifacts: list[str] = field(default_factory=list)
    viz: dict | None = None


# --- front-matter parsing ----------------------------------------------------


def parse_front_matter(text: str) -> dict[str, object] | None:
    """Parse a leading ``---`` YAML front-matter block."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None
    end = None
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            end = i
            break
    if end is None:
        return None

    yaml_text = "\n".join(lines[1:end])
    try:
        return yaml.safe_load(yaml_text)
    except Exception:
        return None


def load_experiment(path: Path) -> Experiment | None:
    """Load one experiment doc into an Experiment, or None if it has no front-matter."""
    meta = parse_front_matter(path.read_text(encoding="utf-8"))
    if meta is None:
        return None

    def scalar(key: str) -> str:
        value = meta.get(key, "")
        return str(value) if value else ""

    artifacts = meta.get("artifacts", [])
    if not isinstance(artifacts, list):
        artifacts = []
    return Experiment(
        slug=path.stem,
        title=scalar("title") or path.stem,
        date=scalar("date"),
        kernel=scalar("kernel"),
        hardware=scalar("hardware"),
        xrt_version=scalar("xrt_version"),
        headline=scalar("headline"),
        artifacts=[str(a) for a in artifacts],
        viz=meta.get("viz"),
    )


def load_experiments(experiments_dir: Path) -> list[Experiment]:
    """Load every experiment doc (excluding the generated index), newest first."""
    out: list[Experiment] = []
    for path in sorted(experiments_dir.glob("*.md")):
        if path.name == "index.md":
            continue
        exp = load_experiment(path)
        if exp is not None:
            out.append(exp)
    # Deterministic order: date descending, then title.
    out.sort(key=lambda e: (e.date, e.title), reverse=True)
    return out


# --- rendering ---------------------------------------------------------------


def render_index_md(experiments: list[Experiment]) -> str:
    lines = [
        "# Evidence Library",
        "",
        GENERATED_NOTE,
        "",
        "Auto-generated index of xdna-top experiment reports. Each entry is a "
        "self-contained, reproducible benchmark grounded in xdna-top evidence "
        "artifacts. Add a new `docs/experiments/<slug>.md` with front-matter and "
        "re-run `tools/build_experiments_index.py` — it appears here automatically.",
        "",
    ]
    if not experiments:
        lines += ["_No experiments yet._", ""]
        return "\n".join(lines)

    lines += [
        "| Experiment | Date | Platform | Headline |",
        "| --- | --- | --- | --- |",
    ]
    for e in experiments:
        platform = f"{e.hardware}, kernel {e.kernel}, XRT {e.xrt_version}".strip(", ")
        headline = e.headline.replace("|", "\\|")
        lines.append(
            f"| [{e.title}]({e.slug}.md) | {e.date} | {platform} | {headline} |"
        )
    lines.append("")

    lines += ["## Raw artifacts", ""]
    for e in experiments:
        if not e.artifacts:
            continue
        lines.append(f"- **{e.title}**")
        for art in e.artifacts:
            lines.append(f"  - [`{art}`]({art})")
    lines.append("")
    return "\n".join(lines)


def render_html_section(experiments: list[Experiment]) -> str:
    rows = []
    for e in experiments:
        platform = f"{e.hardware} · kernel {e.kernel} · XRT {e.xrt_version}"
        headline = _html_escape(e.headline)
        
        if getattr(e, "viz", None) and e.viz.get("type") in ("comparison", "matrix"):
            viz = e.viz
            reproduce_cmd = viz.get("reproduce", "")
            raw_links = [f'<a href="{_html_escape(a)}" style="color: var(--secondary); text-decoration: none; margin-right: 1rem;">📊 Raw artifacts</a>' for a in e.artifacts]
            raw_link_html = raw_links[0] if raw_links else ""
            
            viz_html = ""
            if viz["type"] == "comparison":
                groups_html = []
                for group in viz.get("unit_groups", []):
                    series = group.get("series", {})
                    max_val = max(series.values()) if series else 1
                    bars = ""
                    for key, val in series.items():
                        pct = (val / max_val * 100) if max_val > 0 else 0
                        bg_color = "var(--secondary)" if key == "NPU" else "var(--text-light)"
                        text_color = "inherit" if key == "NPU" else "var(--text-light)"
                        fw = "500" if key == "NPU" else "400"
                        bars += f'''
                        <div style="display: flex; align-items: center; margin-bottom: 0.35rem;">
                          <div style="width: 50px; font-size: 0.85rem; font-weight: {fw}; color: {text_color};">{_html_escape(key)}</div>
                          <div style="flex: 1; background: var(--bg-main); height: 8px; border-radius: 4px; overflow: hidden; margin-right: 0.5rem;">
                            <div style="width: {pct}%; background: {bg_color}; height: 100%;"></div>
                          </div>
                          <div style="width: 50px; text-align: right; font-size: 0.85rem; font-weight: {fw}; color: {text_color};">{val}</div>
                        </div>'''
                    
                    groups_html.append(f'''
                    <div style="flex: 1; min-width: 250px;">
                      <div style="font-weight: 600; color: var(--primary); margin-bottom: 0.25rem;">{_html_escape(group.get("label", ""))} <span style="color: var(--success); margin-left: 0.5rem;">{_html_escape(group.get("highlight", ""))}</span></div>
                      <div style="font-size: 0.8rem; color: var(--text-muted); margin-bottom: 0.75rem;">{_html_escape(group.get("unit", ""))}</div>
                      {bars}
                    </div>''')
                viz_html = f'<div style="display: flex; gap: 2rem; flex-wrap: wrap;">{"".join(groups_html)}</div>'
                
            elif viz["type"] == "matrix":
                cols = viz.get("cols", [])
                rows_labels = viz.get("rows", [])
                data = viz.get("data", [])
                
                ths = "".join(f'<th style="padding: 0.5rem; font-weight: 500; color: var(--text-muted); writing-mode: vertical-rl; transform: rotate(180deg);">{_html_escape(str(c))}</th>' for c in cols)
                
                trs = ""
                for i, r_label in enumerate(rows_labels):
                    tds = ""
                    for val in data[i]:
                        val_float = float(val)
                        t_color = "white" if val_float > 0.5 else "var(--text-main)"
                        tds += f'''
                        <td style="padding: 0.15rem; border-top: 1px solid var(--border-color);">
                          <div style="position: relative; width: 2.5rem; height: 2.5rem; border-radius: 4px; overflow: hidden; display: flex; align-items: center; justify-content: center; font-size: 0.75rem; border: 1px solid var(--border-color);" title="{val_float}">
                            <div style="position: absolute; inset: 0; background: var(--success); opacity: {val_float};"></div>
                            <div style="position: relative; z-index: 1; color: {t_color}; font-weight: 500;">{val_float:.2f}</div>
                          </div>
                        </td>'''
                    trs += f'<tr><td style="padding: 0.5rem; text-align: left; font-weight: 600; color: var(--primary); border-top: 1px solid var(--border-color); white-space: nowrap;">{_html_escape(str(r_label))}</td>{tds}</tr>'
                
                viz_html = f'''
                <div style="overflow-x: auto;">
                  <table style="border-collapse: collapse; text-align: center; font-size: 0.85rem;">
                    <tr>
                      <th style="padding: 0.5rem; text-align: left; color: var(--text-muted); font-weight: 500;">Model \\ Config</th>
                      {ths}
                    </tr>
                    {trs}
                  </table>
                </div>'''

            reproduce_html = (
                f'''<div style="background: var(--primary); color: var(--bg-card); padding: 0.75rem; border-radius: var(--radius-sm); font-family: monospace; font-size: 0.85rem; margin-bottom: 1.5rem; overflow-x: auto;">
            $ {_html_escape(reproduce_cmd)}
          </div>'''
                if reproduce_cmd else ""
            )
            reproduce_link = (
                '<a href="#" style="color: var(--text-muted); text-decoration: none; cursor: default;">⟳ Reproduce</a>'
                if reproduce_cmd else ""
            )

            rows.append(f'''
        <li style="background: var(--bg-card); border: 1px solid var(--border-color); border-radius: var(--radius-md); padding: 1.5rem; margin-bottom: 1.5rem; list-style: none; box-shadow: var(--shadow-sm);">
          <h3 style="margin-top: 0; margin-bottom: 0.5rem; font-size: 1.25rem;"><a href="experiments/{e.slug}.md" style="color: var(--primary); text-decoration: none;">{_html_escape(e.title)}</a></h3>
          <div style="font-size: 0.85rem; color: var(--text-muted); margin-bottom: 1rem; display: flex; align-items: center; gap: 0.5rem; flex-wrap: wrap;">
            <span style="background: var(--accent-light); color: var(--secondary); padding: 0.1rem 0.5rem; border-radius: 4px; border: 1px solid var(--accent-light-border); font-weight: 600;">{_html_escape(e.hardware)}</span>
            <span>Kernel {e.kernel}</span>
            <span>·</span>
            <span>XRT {e.xrt_version}</span>
          </div>
          <div style="margin-bottom: 1.5rem; color: var(--text-main); line-height: 1.5;">
            {_html_escape(e.headline)}
          </div>
          <div style="margin-bottom: 1.5rem;">
            {viz_html}
          </div>
          {reproduce_html}
          <div style="font-size: 0.9rem; font-weight: 500;">
            <a href="experiments/{e.slug}.md" style="color: var(--secondary); text-decoration: none; margin-right: 1.5rem;">📄 Report</a>
            {raw_link_html}
            {reproduce_link}
          </div>
        </li>''')
        else:
            rows.append(
                "        <li class=\"evidence-entry\">\n"
                f"          <a href=\"experiments/{e.slug}.md\"><strong>{_html_escape(e.title)}</strong></a>"
                f" <span class=\"evidence-date\">{_html_escape(e.date)}</span><br>\n"
                f"          <span class=\"evidence-headline\">{headline}</span><br>\n"
                f"          <span class=\"evidence-platform\">{_html_escape(platform)}</span>\n"
                "        </li>"
            )
    body = "\n".join(rows) if rows else "        <li>No experiments yet.</li>"
    return (
        f"{HTML_START}\n"
        "    <section id=\"evidence-library\" class=\"evidence-library\">\n"
        "      <h2>Evidence Library</h2>\n"
        "      <p>Self-contained benchmark reports, each grounded in xdna-top "
        "snapshot/record evidence artifacts. Generated from "
        "<code>docs/experiments/</code>.</p>\n"
        "      <ul class=\"evidence-list\">\n"
        f"{body}\n"
        "      </ul>\n"
        "    </section>\n"
        f"    {HTML_END}"
    )


def inject_html(html_text: str, section: str) -> str:
    """Idempotently replace (or insert) the Evidence Library section by markers."""
    if HTML_START in html_text and HTML_END in html_text:
        start = html_text.index(HTML_START)
        end = html_text.index(HTML_END) + len(HTML_END)
        return html_text[:start] + section + html_text[end:]
    # First run: insert before </body> (or append if no body tag).
    anchor = html_text.rfind("</body>")
    if anchor == -1:
        return html_text.rstrip("\n") + "\n" + section + "\n"
    return html_text[:anchor] + section + "\n  " + html_text[anchor:]


def _html_escape(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


# --- orchestration -----------------------------------------------------------


def build(repo_root: Path, *, check: bool = False) -> int:
    experiments_dir = repo_root / "docs" / "experiments"
    index_path = experiments_dir / "index.md"
    html_path = repo_root / "docs" / "index.html"

    experiments = load_experiments(experiments_dir)
    new_index = render_index_md(experiments)

    new_html = None
    if html_path.exists():
        section = render_html_section(experiments)
        new_html = inject_html(html_path.read_text(encoding="utf-8"), section)

    if check:
        stale = []
        if not index_path.exists() or index_path.read_text(encoding="utf-8") != new_index:
            stale.append(str(index_path))
        if new_html is not None and html_path.read_text(encoding="utf-8") != new_html:
            stale.append(str(html_path))
        if stale:
            print("stale (re-run generator): " + ", ".join(stale), file=sys.stderr)
            return 1
        print("Evidence Library index up to date.")
        return 0

    index_path.write_text(new_index, encoding="utf-8")
    if new_html is not None:
        html_path.write_text(new_html, encoding="utf-8")
    print(
        f"Wrote {index_path} ({len(experiments)} experiment"
        f"{'' if len(experiments) == 1 else 's'})"
        + ("" if new_html is None else f"; injected section into {html_path}")
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if generated outputs are stale (do not write).",
    )
    parser.add_argument(
        "--repo-root",
        default=str(Path(__file__).resolve().parent.parent),
        help="Repository root (defaults to the parent of tools/).",
    )
    args = parser.parse_args()
    return build(Path(args.repo_root), check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
